/** All monetary calculations use integers. Prices are millionths of a yuan. */
export const MAX_SAFE_QUANTITY = 9_007_199_254_740_991n;
export const MAX_CENTS = 99_999_999_999_999_999_999n;
export const MAX_PRICE_MICROS = 99_999_999_999_999_999_999n;

function nonnegative(value: bigint, name: string): void {
  if (value < 0n) throw new RangeError(`${name} must be nonnegative`);
}

function parseDecimal(value: string, scale: number, max: bigint): bigint {
  const pattern = new RegExp(`^(0|[1-9][0-9]*)(?:\\.([0-9]{1,${scale}}))?$`);
  const match = pattern.exec(value);
  if (!match) throw new RangeError('Invalid nonnegative decimal');
  const result = BigInt(match[1]!) * 10n ** BigInt(scale) + BigInt((match[2] ?? '').padEnd(scale, '0'));
  if (result > max) throw new RangeError('Decimal exceeds database precision');
  return result;
}

export function parseMoney(value: string): bigint {
  if (!/^(0|[1-9][0-9]*)\.[0-9]{2}$/.test(value)) throw new RangeError('Money requires exactly two decimals');
  return parseDecimal(value, 2, MAX_CENTS);
}

export function parseUnitPrice(value: string): bigint {
  return parseDecimal(value, 6, MAX_PRICE_MICROS);
}

export function formatMoney(cents: bigint): string {
  const sign = cents < 0n ? '-' : '';
  const value = cents < 0n ? -cents : cents;
  if (value > MAX_CENTS) throw new RangeError('Money exceeds database precision');
  return `${sign}${value / 100n}.${(value % 100n).toString().padStart(2, '0')}`;
}

export function quantity(value: number | bigint, allowZero = false): bigint {
  if (typeof value === 'number' && !Number.isSafeInteger(value)) throw new RangeError('Quantity must be a safe integer');
  const result = BigInt(value);
  if (result < (allowZero ? 0n : 1n) || result > MAX_SAFE_QUANTITY) throw new RangeError('Quantity out of range');
  return result;
}

export function toBaseQuantity(input: number | bigint, multiplier: number | bigint): bigint {
  return quantity(quantity(input) * quantity(multiplier));
}

/** Checks the combined demand too, including repeated product lines. */
export function sumQuantities(values: readonly (number | bigint)[]): bigint {
  return quantity(values.reduce<bigint>((sum, value) => sum + quantity(value, true), 0n), true);
}

export function roundHalfUp(numerator: bigint, denominator: bigint): bigint {
  nonnegative(numerator, 'numerator');
  if (denominator <= 0n) throw new RangeError('Denominator must be positive');
  return (numerator * 2n + denominator) / (denominator * 2n);
}

/** Converts original price/unit and multiplier directly to cents, without rounding base price. */
export function amountForBaseQuantity(priceMicros: bigint, multiplier: bigint, baseQuantity: bigint): bigint {
  if (priceMicros > MAX_PRICE_MICROS) throw new RangeError('Price out of range');
  nonnegative(priceMicros, 'price');
  quantity(multiplier);
  quantity(baseQuantity, true);
  const cents = roundHalfUp(priceMicros * baseQuantity, multiplier * 10_000n);
  if (cents > MAX_CENTS) throw new RangeError('Amount out of range');
  return cents;
}

/** Maximum remainder apportionment; ties use input order. */
export function allocateDiscount(lineAmounts: readonly bigint[], discount: bigint): bigint[] {
  nonnegative(discount, 'discount');
  for (const amount of lineAmounts) {
    nonnegative(amount, 'line amount');
    if (amount > MAX_CENTS) throw new RangeError('Amount out of range');
  }
  const total = lineAmounts.reduce((sum, value) => sum + value, 0n);
  if (total > MAX_CENTS || discount > total) throw new RangeError('Discount exceeds amount or monetary range');
  if (total === 0n) return lineAmounts.map(() => 0n);
  const result = lineAmounts.map(value => value * discount / total);
  const order = lineAmounts.map((value, index) => ({index, remainder: value * discount % total}))
    .sort((a, b) => a.remainder === b.remainder ? a.index - b.index : a.remainder > b.remainder ? -1 : 1);
  const extra = discount - result.reduce((sum, value) => sum + value, 0n);
  for (let i = 0; i < Number(extra); i++) result[order[i]!.index]! += 1n;
  return result;
}

export interface AmountSource {
  quantity: bigint;
  amount: bigint;
  allocatedQuantity: bigint;
  allocatedAmount: bigint;
}

/** Persist the returned counters alongside the source in the same transaction. */
export function allocateFromSource(source: Readonly<AmountSource>, requested: bigint): {amount: bigint; source: AmountSource} {
  quantity(source.quantity);
  quantity(source.allocatedQuantity, true);
  quantity(requested);
  nonnegative(source.amount, 'source amount');
  nonnegative(source.allocatedAmount, 'allocated amount');
  if (source.amount > MAX_CENTS || source.allocatedQuantity > source.quantity || source.allocatedAmount > source.amount)
    throw new RangeError('Invalid source counters');
  // Counters must have been generated by this cumulative algorithm, preventing corrupted tails.
  if (source.allocatedAmount !== roundHalfUp(source.amount * source.allocatedQuantity, source.quantity))
    throw new RangeError('Inconsistent source allocation');
  const nextQuantity = source.allocatedQuantity + requested;
  if (nextQuantity > source.quantity) throw new RangeError('Allocation exceeds original source');
  const nextAmount = roundHalfUp(source.amount * nextQuantity, source.quantity);
  return {amount: nextAmount - source.allocatedAmount, source: {...source, allocatedQuantity: nextQuantity, allocatedAmount: nextAmount}};
}

/** Returns are allocated against the original issued amount, never the current price. */
export const returnFromSource = allocateFromSource;
